#!/usr/bin/env python3
"""
Rebuild the static DocVault demo (this folder) from ../public.

The demo is the normal front end plus js/mock-api.js, a fake backend that runs in the
browser and keeps its data in localStorage, so the site can be hosted on Netlify or any
other static host without the Python server. Run this after changing anything in public/:

    python3 demo/build.py

It copies public/css and public/js, and the five HTML pages with the mock script tag
inserted before the first <script>. The login pages become student/login/index.html and
teacher/login/index.html so that /student/login works on a plain static server too.
Only js/mock-api.js and this script are hand-written; everything else here is generated.
"""
import os
import shutil

DEMO = os.path.dirname(os.path.abspath(__file__))
PUBLIC = os.path.join(os.path.dirname(DEMO), "public")
TAG = '<script src="/js/mock-api.js"></script>'
NOTE = "<!-- Generated by demo/build.py from public/%s - edit the original, then rebuild. -->\n"
PAGES = {
    "index.html": "index.html",
    "student/index.html": "student/index.html",
    "student/login.html": "student/login/index.html",
    "teacher/index.html": "teacher/index.html",
    "teacher/login.html": "teacher/login/index.html",
}
REDIRECTS = """# Netlify: clean URLs for the DocVault demo (both portals on one site).
# Existing files always win over these rules, so /css, /js and the pages themselves are served as-is.
/student/login   /student/login/index.html   200
/teacher/login   /teacher/login/index.html   200
/student/*       /student/index.html         200
/teacher/*       /teacher/index.html         200
"""


def copy_tree(src, dst):
    os.makedirs(dst, exist_ok=True)
    for name in os.listdir(src):
        if name.startswith("."):
            continue
        shutil.copy2(os.path.join(src, name), os.path.join(dst, name))


def main():
    copy_tree(os.path.join(PUBLIC, "css"), os.path.join(DEMO, "css"))
    copy_tree(os.path.join(PUBLIC, "js"), os.path.join(DEMO, "js"))
    for src, dst in PAGES.items():
        with open(os.path.join(PUBLIC, src), encoding="utf-8") as fh:
            html = fh.read()
        idx = html.find("<script")
        if idx < 0:
            raise SystemExit(f"{src}: no <script> tag found")
        html = html[:idx] + TAG + "\n  " + html[idx:]
        html = html.replace("<!doctype html>\n", "<!doctype html>\n" + NOTE % src, 1)
        out = os.path.join(DEMO, dst)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(html)
    with open(os.path.join(DEMO, "_redirects"), "w", encoding="utf-8") as fh:
        fh.write(REDIRECTS)
    print(f"Demo rebuilt in {DEMO}")


if __name__ == "__main__":
    main()
